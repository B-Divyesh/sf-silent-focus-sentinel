import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const arguments_ = process.argv.slice(2);
const outputIndex = arguments_.indexOf('--output');
const binaryIndex = arguments_.indexOf('--binary');
const output = outputIndex >= 0
  ? resolve(arguments_[outputIndex + 1])
  : resolve(root, 'site/public/demo-recording.svg');
const binary = binaryIndex >= 0
  ? resolve(arguments_[binaryIndex + 1])
  : resolve(root, 'target/release/silent-focus-sentinel');

if (!arguments_.every((argument, index) => argument !== '--output' && argument !== '--binary' || Boolean(arguments_[index + 1]))) {
  throw new Error('Use --output <file> and --binary <file> with a value.');
}

const transcript = execFileSync(binary, ['demo'], { encoding: 'utf8' })
  .trim()
  .replace(/\/tmp\/silent-focus-sentinel-demo-[^/]+/g, '/tmp/silent-focus-sentinel-demo-…');
const lines = ['$ silent-focus-sentinel demo', '', ...transcript.split('\n')];
const escapeXml = (value) => value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');
const lineMarkup = lines.map((line, index) => {
  const color = line.startsWith('$') ? '#71f2d0' : line.startsWith('Found') ? '#ff8f7b' : line.startsWith('JSON:') || line.startsWith('HTML:') ? '#aac1d4' : '#dcecf8';
  return `<text x="34" y="${104 + index * 41}" fill="${color}">${escapeXml(line)}</text>`;
}).join('');
const description = `Terminal recording generated by running silent-focus-sentinel demo: ${lines.join(' ')}`;
const svg = `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" width="760" height="420" viewBox="0 0 760 420" role="img" aria-labelledby="title description">
  <title id="title">Silent Focus Sentinel CLI demo recording</title>
  <desc id="description">${escapeXml(description)}</desc>
  <rect width="760" height="420" rx="14" fill="#050c16"/>
  <path d="M14 0h732a14 14 0 0 1 14 14v42H0V14A14 14 0 0 1 14 0Z" fill="#0e2238"/>
  <circle cx="27" cy="28" r="5" fill="#294860"/><circle cx="45" cy="28" r="5" fill="#294860"/><circle cx="63" cy="28" r="5" fill="#294860"/>
  <text x="88" y="33" fill="#aac1d4" font-family="ui-monospace, SFMono-Regular, Consolas, monospace" font-size="15">silent-focus-sentinel — demo</text>
  <g font-family="ui-monospace, SFMono-Regular, Consolas, monospace" font-size="16" xml:space="preserve">${lineMarkup}</g>
</svg>\n`;

mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, svg);
console.log(`Recorded ${binary} demo to ${output}`);
